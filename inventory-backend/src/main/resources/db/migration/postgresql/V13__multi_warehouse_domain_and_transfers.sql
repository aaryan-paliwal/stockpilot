-- 1. Ensure products has UNIQUE (id, user_id) for composite foreign key references
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'uq_products_id_user'
    ) THEN
        ALTER TABLE products ADD CONSTRAINT uq_products_id_user UNIQUE (id, user_id);
    END IF;
END $$;

-- 2. Create warehouses table
CREATE TABLE IF NOT EXISTS warehouses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    address VARCHAR(255),
    city VARCHAR(100),
    state VARCHAR(100),
    postal_code VARCHAR(30),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_warehouses_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uq_warehouses_user_code UNIQUE (user_id, code),
    CONSTRAINT uq_warehouses_id_user UNIQUE (id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_warehouses_user ON warehouses(user_id);
CREATE INDEX IF NOT EXISTS idx_warehouses_user_code ON warehouses(user_id, code);

-- 3. Create dedicated warehouse_inventory table (user_id + warehouse_id + product_id + quantity)
CREATE TABLE IF NOT EXISTS warehouse_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    qty INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_warehouse_inventory_wh_prod UNIQUE (warehouse_id, product_id),
    CONSTRAINT chk_warehouse_inventory_qty_non_negative CHECK (qty >= 0),
    CONSTRAINT fk_wh_inv_warehouse_user FOREIGN KEY (warehouse_id, user_id) REFERENCES warehouses(id, user_id) ON DELETE CASCADE,
    CONSTRAINT fk_wh_inv_product_user FOREIGN KEY (product_id, user_id) REFERENCES products(id, user_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_warehouse_inv_wh ON warehouse_inventory(warehouse_id);
CREATE INDEX IF NOT EXISTS idx_warehouse_inv_prod ON warehouse_inventory(product_id);
CREATE INDEX IF NOT EXISTS idx_warehouse_inv_user ON warehouse_inventory(user_id);

-- 4. Enhance stock_transactions with warehouse_id
ALTER TABLE stock_transactions
    ADD COLUMN IF NOT EXISTS warehouse_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_stock_tx_warehouse_user'
    ) THEN
        ALTER TABLE stock_transactions
            ADD CONSTRAINT fk_stock_tx_warehouse_user
            FOREIGN KEY (warehouse_id, user_id)
            REFERENCES warehouses(id, user_id)
            ON DELETE SET NULL;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_stock_transactions_wh_id ON stock_transactions (warehouse_id);

-- 5. Create warehouse_transfers table
CREATE TABLE IF NOT EXISTS warehouse_transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    source_warehouse_id BIGINT NOT NULL,
    dest_warehouse_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    qty INT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'INITIATED',
    reference_note VARCHAR(255),
    initiating_user VARCHAR(100) NOT NULL,
    approving_user VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT chk_transfers_qty_positive CHECK (qty > 0),
    CONSTRAINT chk_transfers_different_warehouses CHECK (source_warehouse_id <> dest_warehouse_id),
    CONSTRAINT fk_transfers_source_wh_user FOREIGN KEY (source_warehouse_id, user_id) REFERENCES warehouses(id, user_id),
    CONSTRAINT fk_transfers_dest_wh_user FOREIGN KEY (dest_warehouse_id, user_id) REFERENCES warehouses(id, user_id),
    CONSTRAINT fk_transfers_product_user FOREIGN KEY (product_id, user_id) REFERENCES products(id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_transfers_user_status ON warehouse_transfers(user_id, status);
CREATE INDEX IF NOT EXISTS idx_transfers_prod ON warehouse_transfers(product_id);

-- 6. Backfill Default Warehouse for existing users with products
DO $$
DECLARE
    u_rec RECORD;
    v_wh_id BIGINT;
    p_rec RECORD;
BEGIN
    FOR u_rec IN SELECT DISTINCT user_id FROM products WHERE user_id IS NOT NULL LOOP
        -- Check if user already has a default warehouse
        SELECT id INTO v_wh_id FROM warehouses WHERE user_id = u_rec.user_id AND code = 'WH-DEFAULT';
        IF v_wh_id IS NULL THEN
            INSERT INTO warehouses (user_id, code, name, description, address, city, state, postal_code, is_active)
            VALUES (u_rec.user_id, 'WH-DEFAULT', 'Primary Default Warehouse', 'Default migration warehouse', '100 Main St', 'Central', 'CA', '90001', TRUE)
            RETURNING id INTO v_wh_id;
        END IF;

        -- For each product belonging to this user, if qty > 0, backfill into warehouse_inventory
        FOR p_rec IN SELECT id, qty FROM products WHERE user_id = u_rec.user_id LOOP
            INSERT INTO warehouse_inventory (user_id, warehouse_id, product_id, qty)
            VALUES (u_rec.user_id, v_wh_id, p_rec.id, p_rec.qty)
            ON CONFLICT (warehouse_id, product_id) DO NOTHING;
        END LOOP;
    END LOOP;
END $$;

