-- -----------------------------------------------------
-- Table `stock_transactions`
-- -----------------------------------------------------
CREATE TABLE stock_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    type VARCHAR(10) NOT NULL, -- 'IN' or 'OUT'
    product_id BIGINT NOT NULL,
    qty INT NOT NULL,
    created_by VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_stock_transactions_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_stock_transactions_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

