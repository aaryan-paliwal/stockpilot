-- 1. Create product_batches table
CREATE TABLE IF NOT EXISTS product_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    batch_number VARCHAR(100) NOT NULL,
    mfg_date DATE,
    expiry_date DATE,
    cost_price NUMERIC(15, 4) NOT NULL DEFAULT 0.0000,
    is_cost_estimated BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_product_batches_user_prod_batch UNIQUE (user_id, product_id, batch_number),
    CONSTRAINT uq_product_batches_id_user UNIQUE (id, user_id),
    CONSTRAINT uq_product_batches_id_prod_user UNIQUE (id, product_id, user_id),
    CONSTRAINT fk_batches_product_user FOREIGN KEY (product_id, user_id) REFERENCES products(id, user_id) ON DELETE CASCADE,
    CONSTRAINT chk_batch_status CHECK (status IN ('ACTIVE', 'QUARANTINED', 'EXPIRED', 'DEPLETED', 'ARCHIVED')),
    CONSTRAINT chk_batch_cost_price_non_negative CHECK (cost_price >= 0),
    CONSTRAINT chk_batch_dates CHECK (expiry_date IS NULL OR mfg_date IS NULL OR expiry_date >= mfg_date)
);

CREATE INDEX IF NOT EXISTS idx_product_batches_expiry ON product_batches (expiry_date);
CREATE INDEX IF NOT EXISTS idx_product_batches_user_prod ON product_batches (user_id, product_id);

-- 2. Create batch_inventory table (with strict 3-column composite FK to product_batches)
CREATE TABLE IF NOT EXISTS batch_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    qty INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_batch_inventory_batch_warehouse UNIQUE (batch_id, warehouse_id),
    CONSTRAINT chk_batch_inv_qty_non_negative CHECK (qty >= 0),
    CONSTRAINT fk_batch_inv_batch_prod_user 
        FOREIGN KEY (batch_id, product_id, user_id) 
        REFERENCES product_batches(id, product_id, user_id) 
        ON DELETE RESTRICT,
    CONSTRAINT fk_batch_inv_wh_user 
        FOREIGN KEY (warehouse_id, user_id) 
        REFERENCES warehouses(id, user_id) 
        ON DELETE CASCADE,
    CONSTRAINT fk_batch_inv_prod_user 
        FOREIGN KEY (product_id, user_id) 
        REFERENCES products(id, user_id) 
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_batch_inv_wh ON batch_inventory (warehouse_id);
CREATE INDEX IF NOT EXISTS idx_batch_inv_prod ON batch_inventory (product_id);
CREATE INDEX IF NOT EXISTS idx_batch_inv_batch ON batch_inventory (batch_id);

-- 3. Enhance stock_transactions with batch attribution (RESTRICT delete behavior)
ALTER TABLE stock_transactions
    ADD COLUMN IF NOT EXISTS batch_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_stock_tx_batch_user'
    ) THEN
        ALTER TABLE stock_transactions
            ADD CONSTRAINT fk_stock_tx_batch_user
            FOREIGN KEY (batch_id, user_id)
            REFERENCES product_batches(id, user_id)
